                        #:   서명에 넣는다. 이름만 쓰면 같은 이름("보통약관")을 쓰는
                        #:   서로 다른 두 특약의 정당한 조항이 서로 "중복 제목
                        #:   자기참조"로 오판된다(위 `_section_context_at` 주석 참조).
                        sig = (sec_idx, m.group(1), m.group(2) or "", title_norm)
