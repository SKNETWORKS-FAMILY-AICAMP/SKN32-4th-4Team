            #:     쓰는 조사다 — 진짜 조 본문(①…, 회사는 …)은 이렇게 시작하지 않는다.
            #:
            #:   ★★**제목에 괄호가 중첩되면 검사를 건너뛴다.** `_ARTICLE` 의 제목
            #:     캡처는 `)` 를 못 담아서 `납입최고(독촉)와 계약의 해지` 같은 제목이
            #:     `납입최고(독촉` 에서 잘리고 **남은 `와 계약의 해지)` 가 꼬리로
