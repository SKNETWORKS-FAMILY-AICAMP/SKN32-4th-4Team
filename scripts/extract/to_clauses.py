            #:     되돌아간다. 제목 정규식 자체(중첩 괄호 미지원)를 고치는 게
            #:     근본 해법이지만 영향 범위가 더 넓어 이번 범위 밖으로 둔다.
            title_head = (m.group(3) or "")
