"""표지 이름 대조 — **흔들어도 되는 것과 안 되는 것.**

참고 — 이 파일이 지키는 명제

    1. 위험 — 판본 토큰이 다르면 **무조건** 탈락한다. 다른 무엇을 허용해도 이건 안 흔든다.
    2. 위험 — 정체성 부기(계약전환용·단체전환용…)는 표지에 **있어야** 한다.
    3. 판매채널 부기 `(CM)`·`(TM)` 는 표지가 생략해도 된다.
    4. 표지가 더 쓰는 연결 낱말(보험·보장·비)의 **삽입**은 봐준다.
    5. 판본을 모르면 자동 확정하지 않는다 — 「모른다」를 「맞다」로 바꾸지 않는다.
    6. 대조 범위는 **한 줄 또는 인접 두 줄**이다. 흩어진 토큰은 증거가 아니다.

핵심 — 왜 이 시험이 있나 (전수 실측 2026-08-11)

    「전체 상품명이 문서에 한 덩어리로 나오지 않는다」 286건의 정체는
    조판도 추출 실패도 아니었다. **이름 출처가 둘**이다 —
    매니페스트는 보험사 **공시 목록** 표기, 문서는 약관 **표지** 표기.

        매니페스트: 무배당 프로미라이프 실손의료비(기본납입형)1304
        표지      : 무배당 프로미라이프 실손의료비**보험**(기본납입형)1304

    147건 괄호 부기 차이 · 79건 낱말 하나 · 38건 글자 하나 · 22건 판본 관련.

    위험 — 그 안에 **진짜 오류**가 섞여 있다 —

        매니페스트: 실손의료비보장 안정화 할인 특별약관2507
        표지      : 실손의료비보장 안정화 할인 특별약관2510

    이름은 글자 하나까지 같고 판본만 다르다. 통과시키면 **2507 가입자에게
    2510 약관으로 답한다.** 그래서 판본을 불변식으로 둔다.
"""

from __future__ import annotations

import pytest

from scripts.confirm.identify_documents import (
    _VERSION, _norm, cover_match, cover_windows, full_name_key, version_tokens,
)


def test_판본을_이름에서_떼어낼_수_있다():
    """위험 — `\\b` 는 한글과 숫자 사이에서 성립하지 않는다.

    참고 — 처음 판본 충돌 검사를 `\\(?\\b\\d{2}[.\\-]?\\d{2}\\b\\)?` 로 썼더니 **아무것도 떼지
      못했다.** 「특별약관2507」에서 `관` 과 `2` 는 둘 다 낱말 문자라 경계가 없다.
      그래서 충돌 검사가 조용히 0건을 내놓았고, 2507↔2510 을 놓쳤다.
    """
    stem = _norm(_VERSION.sub(" ", "실손의료비보장 안정화 할인 특별약관2507"))
    assert "2507" not in stem
    assert stem in _norm("실손의료비보장 안정화 할인 특별약관2510")


# ── ① 위험 — 판본 불변식 ──────────────────────────────────────────────────────
def test_판본이_다르면_이름이_같아도_탈락한다():
    #: 실측 사례 — 이름은 글자 하나까지 같고 판본만 2507 대 2510 이다.
    assert not cover_match("실손의료비보장 안정화 할인 특별약관2507",
                           "실손의료비보장 안정화 할인 특별약관2510")


