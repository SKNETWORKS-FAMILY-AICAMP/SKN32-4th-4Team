def test_상품군_열쇠는_판본과_채널을_뺀다():
    from scripts.confirm.identify_documents import family_key
    a = family_key("무배당 프로미라이프 실손의료비보험2404(CM)")
    b = family_key("무배당 프로미라이프 실손의료비보험2605(TM)")
    assert a == b, "판본과 채널만 다르면 같은 상품군이다"
    #: 위험 — 정체성 부기는 상품군을 **가른다** — 다른 상품이므로.
